"""CC Journal — deployment generator.

Usage:
    sudo python3 deploy.py

Asks for a deployment name (e.g. "ahuspus") and produces deployment files named
after it:

    <name>.service      systemd unit running gunicorn
    <name>.nginx        nginx server block (reverse proxy + static/media)
    <name>.socket       (optional) systemd socket for gunicorn

It collects static files, then writes the units and prints the exact commands to
enable them. Nothing is enabled automatically unless you confirm.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VENV = ROOT / "venv"
DEPLOY_DIR = ROOT / "deploy"
IS_TTY = sys.stdin.isatty()


class C:
    G = "\033[92m"; Y = "\033[93m"; R = "\033[91m"; B = "\033[94m"; D = "\033[2m"; X = "\033[0m"


def say(m): print(f"{C.B}▸{C.X} {m}")
def ok(m): print(f"{C.G}✓{C.X} {m}")
def warn(m): print(f"{C.Y}!{C.X} {m}")
def die(m): print(f"{C.R}✗ {m}{C.X}"); sys.exit(1)


def prompt(question: str, default: str = "") -> str:
    if not IS_TTY:
        return default
    d = f" [{default}]" if default else ""
    try:
        ans = input(f"{C.Y}?{C.X} {question}{d} ").strip()
    except EOFError:
        return default
    return ans or default


def ask_yn(question: str, default: bool = False) -> bool:
    if not IS_TTY:
        return default
    suffix = "Y/n" if default else "y/N"
    try:
        a = input(f"{C.Y}?{C.X} {question} [{suffix}] ").strip().lower()
    except EOFError:
        return default
    return default if not a else a in ("y", "yes")


def slugify(name: str) -> str:
    out = "".join(c if (c.isalnum() or c in "-_") else "-" for c in name.strip().lower())
    out = out.strip("-_")
    return out or "ccjournal"


def venv_python() -> Path:
    return VENV / "bin" / "python"


def gunicorn_bin() -> Path:
    return VENV / "bin" / "gunicorn"


SERVICE_TMPL = """\
# {name}.service — CC Journal (gunicorn). Generated by deploy.py.
[Unit]
Description=CC Journal ({name}) — gunicorn
After=network.target

[Service]
Type=simple
User={user}
Group={group}
WorkingDirectory={root}
Environment=DJANGO_SETTINGS_MODULE=config.settings
# Şema her başlangıçta güncellenir — "kod yeni, migration eski" 500'lerini imkânsız kılar.
ExecStartPre={python} {root}/manage.py migrate --noinput
ExecStart={gunicorn} config.wsgi:application \\
    --bind {bind} \\
    --workers {workers} \\
    --timeout 60 \\
    --access-logfile - --error-logfile -
Restart=on-failure
RestartSec=3
# Hardening
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
"""

NGINX_TMPL = """\
# {name}.nginx — CC Journal reverse proxy. Generated by deploy.py.
server {{
    listen 80;
    server_name {server_name};

    client_max_body_size 50M;

    location /static/ {{
        alias {root}/staticfiles/;
        expires 30d;
        access_log off;
    }}
    location /media/ {{
        alias {root}/media/;
        expires 7d;
    }}

    location / {{
        proxy_pass http://{bind};
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_redirect off;
    }}
}}
"""


def collect_static(user):
    say("Collecting static files…")
    py = str(venv_python())
    cmd = [py, str(ROOT / "manage.py"), "collectstatic", "--noinput"]
    if user and os.geteuid() == 0:
        cmd = ["sudo", "-u", user, "-H"] + cmd
    try:
        subprocess.run(cmd, check=True)
        ok("Static files collected.")
    except subprocess.CalledProcessError:
        warn("collectstatic failed; continuing.")


def main():
    print(f"{C.B}{'='*52}{C.X}")
    print(f"{C.B}  CC Journal — deployment generator{C.X}")
    print(f"{C.B}{'='*52}{C.X}\n")

    if not VENV.exists():
        die("No virtual environment found. Run: sudo python3 install.py first.")
    if not gunicorn_bin().exists():
        warn("gunicorn not found in venv; it should be in requirements.txt.")

    raw = prompt("Deployment name (used for file names, e.g. ahuspus):", "ccjournal")
    name = slugify(raw)
    if name != raw:
        warn(f"Normalised to '{name}'.")

    default_user = os.environ.get("SUDO_USER") or os.environ.get("USER") or "www-data"
    user = prompt("Run as system user:", default_user)
    group = prompt("System group:", user)
    server_name = prompt("Domain / server_name:", "_")
    bind = prompt("gunicorn bind (host:port):", "127.0.0.1:8000")
    workers = prompt("gunicorn workers:", "3")

    DEPLOY_DIR.mkdir(exist_ok=True)
    ctx = dict(name=name, user=user, group=group, root=str(ROOT),
               gunicorn=str(gunicorn_bin()), python=str(venv_python()),
               bind=bind, workers=workers, server_name=server_name)

    service_path = DEPLOY_DIR / f"{name}.service"
    nginx_path = DEPLOY_DIR / f"{name}.nginx"
    service_path.write_text(SERVICE_TMPL.format(**ctx))
    nginx_path.write_text(NGINX_TMPL.format(**ctx))
    ok(f"Wrote {service_path.relative_to(ROOT)}")
    ok(f"Wrote {nginx_path.relative_to(ROOT)}")

    collect_static(os.environ.get("SUDO_USER"))

    installed = False
    if os.geteuid() == 0 and ask_yn("Install the systemd service and enable it now?", default=False):
        target = Path("/etc/systemd/system") / f"{name}.service"
        shutil.copy(service_path, target)
        subprocess.run(["systemctl", "daemon-reload"], check=False)
        subprocess.run(["systemctl", "enable", "--now", f"{name}.service"], check=False)
        ok(f"Installed and started {name}.service")
        installed = True

    nginx_installed = False
    if os.geteuid() == 0 and Path("/etc/nginx").exists() and \
            ask_yn("Install the nginx site and reload nginx?", default=False):
        avail = Path("/etc/nginx/sites-available")
        enabled = Path("/etc/nginx/sites-enabled")
        if avail.exists() and enabled.exists():
            shutil.copy(nginx_path, avail / name)
            link = enabled / name
            if not link.exists():
                link.symlink_to(avail / name)
        else:
            shutil.copy(nginx_path, Path("/etc/nginx/conf.d") / f"{name}.conf")
        subprocess.run(["nginx", "-t"], check=False)
        subprocess.run(["systemctl", "reload", "nginx"], check=False)
        ok("nginx site installed and reloaded.")
        nginx_installed = True

    print()
    ok("Deployment files ready.")
    print(f"""
{C.D}Generated in ./deploy/:{C.X}
  • {name}.service   {C.D}systemd unit (gunicorn){C.X}
  • {name}.nginx     {C.D}nginx reverse proxy{C.X}
""")
    if not installed:
        print(f"""{C.D}To install manually:{C.X}
  sudo cp deploy/{name}.service /etc/systemd/system/
  sudo systemctl daemon-reload && sudo systemctl enable --now {name}.service""")
    if not nginx_installed:
        print(f"""  sudo cp deploy/{name}.nginx /etc/nginx/sites-available/{name}
  sudo ln -s /etc/nginx/sites-available/{name} /etc/nginx/sites-enabled/{name}
  sudo nginx -t && sudo systemctl reload nginx""")
    print(f"\n{C.D}Then add TLS with certbot:{C.X}  sudo certbot --nginx -d {server_name}")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nAborted.")
        sys.exit(130)
